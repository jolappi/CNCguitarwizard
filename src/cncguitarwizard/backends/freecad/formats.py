"""The finished FreeCAD model in other 3D formats, exported on its own.

The build's FreeCAD script makes ``Prototype001.FCStd`` and its STEP; a
format export script, run in FreeCAD beside that model afterwards, writes
it in the other common 3D formats: each solid part shown in the model
(the body, the neck, the fretboard) a file of its own, and the whole
guitar one more, named as the STEP is (``Prototype001_Body.stl``,
``Prototype001.stl``). It does not build anything again, so it takes
seconds.
"""

from __future__ import annotations

import json
from collections.abc import Sequence

from .exceptions import FreeCADBackendError

EXPORT_FORMATS: dict[str, str] = {
    "step": "STEP: CAD and CAM, its surfaces exact, each part on its own too",
    "stl": "STL: 3D printing, slicers and most CAM",
    "3mf": "3MF: 3D printing, its units kept",
    "obj": "OBJ: Blender and rendering",
    "glb": "GLB (glTF): 3D viewers on the web and phones, in colour",
    "iges": "IGES: older CAD and CAM, its surfaces exact",
    "brep": "BREP: FreeCAD and OpenCascade, exact",
}
"""The formats a model can be exported to, by file extension, and what
each is for."""

MESH_FORMATS = frozenset({"stl", "3mf", "obj"})
"""The formats that hold a mesh of triangles rather than exact surfaces."""

MESH_LINEAR_DEFLECTION = 0.05
"""How far a mesh's triangles may stray from the exact surface, in mm."""

MESH_ANGULAR_DEFLECTION = 0.25
"""How far, in radians, a mesh's neighbouring triangles may turn."""

MODEL_DOCUMENT = "Prototype001.FCStd"
"""The finished model an export script reads."""


def export_script_name(formats: Sequence[str]) -> str:
    """Return an export script's file name: one format's own
    (``Prototype001_export_stl.py``), or ``Prototype001_export.py``."""
    if len(formats) == 1:
        return f"Prototype001_export_{formats[0]}.py"
    return "Prototype001_export.py"


def render_format_export(formats: Sequence[str]) -> str:
    """Return a FreeCAD script exporting the finished model to ``formats``.

    Run in FreeCAD (``freecadcmd``, or as a macro) it uses the model open
    there, else ``MODEL_DOCUMENT`` beside the script or in the working
    folder, and writes every solid part shown in it, and the whole of
    them, in each format beside the model: a mesh within
    ``MESH_LINEAR_DEFLECTION`` of the surface for ``MESH_FORMATS``, the
    exact surfaces for the others. It prints a ``WROTE`` line for each
    file.

    Args:
        formats: ``EXPORT_FORMATS`` keys, each once.

    Returns:
        Standalone Python source for execution inside FreeCAD.

    Raises:
        FreeCADBackendError: For no format, an unknown one or one twice.
    """
    if not formats:
        raise FreeCADBackendError("Choose at least one format to export to.")
    unknown = [name for name in formats if name not in EXPORT_FORMATS]
    if unknown:
        raise FreeCADBackendError(
            f"Unknown 3D format {', '.join(unknown)}: choose from "
            f"{', '.join(EXPORT_FORMATS)}."
        )
    if len(set(formats)) != len(formats):
        raise FreeCADBackendError("Each format is exported once.")
    return (
        '"""Generated by CNCguitarwizard. Do not edit manually.\n\n'
        f"Exports {MODEL_DOCUMENT} to {', '.join(formats)}: run it in FreeCAD\n"
        "beside the model, after the build's own script has made it.\n"
        '"""\n\n'
        "import os\n\n"
        "import FreeCAD as App\n"
        "import Import\n"
        "import Mesh\n"
        "import MeshPart\n"
        "import Part\n\n"
        f"FORMATS = {json.dumps(list(formats))}\n"
        f"MESH_FORMATS = {json.dumps(sorted(MESH_FORMATS))}\n"
        f'DOCUMENT = "{MODEL_DOCUMENT}"\n'
        f"LINEAR_DEFLECTION = {MESH_LINEAR_DEFLECTION!r}\n"
        f"ANGULAR_DEFLECTION = {MESH_ANGULAR_DEFLECTION!r}\n\n\n"
        "def model():\n"
        '    """Return the model: open in FreeCAD, or read beside this script."""\n'
        "    for document in App.listDocuments().values():\n"
        "        if os.path.basename(document.FileName) == DOCUMENT:\n"
        "            return document\n"
        "    folders = [os.getcwd()]\n"
        '    if "__file__" in globals():\n'
        "        folders.insert(0, os.path.dirname(os.path.abspath(__file__)))\n"
        "    for folder in folders:\n"
        "        path = os.path.join(folder, DOCUMENT)\n"
        "        if os.path.isfile(path):\n"
        "            return App.openDocument(path)\n"
        "    raise RuntimeError(\n"
        '        f"{DOCUMENT} was not found: run the build\'s "\n'
        '        "Prototype001_freecad.py first, then this script beside the "\n'
        '        "model it makes."\n'
        "    )\n\n\n"
        "def mesh(shapes):\n"
        '    """Return one mesh of the shapes, within LINEAR_DEFLECTION."""\n'
        "    whole = Mesh.Mesh()\n"
        "    for shape in shapes:\n"
        "        whole.addMesh(\n"
        "            MeshPart.meshFromShape(\n"
        "                Shape=shape,\n"
        "                LinearDeflection=LINEAR_DEFLECTION,\n"
        "                AngularDeflection=ANGULAR_DEFLECTION,\n"
        "                Relative=False,\n"
        "            )\n"
        "        )\n"
        "    return whole\n\n\n"
        "def export(objects, path, extension):\n"
        '    """Write the objects\' shapes to path in the format of extension."""\n'
        "    shapes = [part.Shape for part in objects]\n"
        "    if extension in MESH_FORMATS:\n"
        "        mesh(shapes).write(path)\n"
        '    elif extension == "brep":\n'
        "        Part.Compound(shapes).exportBrep(path)\n"
        '    elif extension in ("iges", "step"):\n'
        "        Part.export(objects, path)\n"
        "    else:\n"
        "        Import.export(objects, path)\n"
        '    print(f"WROTE {os.path.basename(path)}")\n\n\n'
        "document = model()\n"
        "folder = os.path.dirname(document.FileName)\n"
        "stem = os.path.splitext(DOCUMENT)[0]\n"
        "# Every solid part shown in the model, as the STEP has them.\n"
        "parts = [\n"
        "    part\n"
        "    for part in document.Objects\n"
        '    if part.isDerivedFrom("Part::Feature")\n'
        "    and part.Visibility\n"
        "    and not part.Shape.isNull()\n"
        "    and part.Shape.Solids\n"
        "]\n"
        "if not parts:\n"
        '    raise RuntimeError(f"{DOCUMENT} has no solid part to export.")\n'
        "for extension in FORMATS:\n"
        "    for part in parts:\n"
        '        name = f"{stem}_{part.Label}.{extension}"\n'
        "        export([part], os.path.join(folder, name), extension)\n"
        '    export(parts, os.path.join(folder, f"{stem}.{extension}"), extension)\n'
    )
