"""The finished model measured in FreeCAD, for the build to check.

The build's FreeCAD script makes ``Prototype001.FCStd`` and its STEP. The
measuring script, run in FreeCAD beside them afterwards, opens the model,
reads the STEP back into a shape of its own and prints what it finds as
one JSON line (``MEASURED_PREFIX``): each solid part shown in the model
(the parts the STEP and the other 3D formats hold), the STEP's solids
and box, and whether the model holds its ``Parameters`` spreadsheet. It
changes nothing; judging what it found is the build's
(``workflows.model_check``).
"""

from __future__ import annotations

import json
from typing import Any

MEASURE_SCRIPT_NAME = "Prototype001_check.py"
"""The measuring script's file name, beside the model."""

MEASURED_PREFIX = "MEASURED "
"""The start of the line the measuring script prints its JSON on."""


def render_model_measure() -> str:
    """Return a FreeCAD script that measures the finished model.

    Run in FreeCAD (``freecadcmd``) beside ``Prototype001.FCStd`` and
    ``Prototype001.step``, it prints ``MEASURED_PREFIX`` and a JSON
    object: ``parts`` (each solid part shown, by name: ``valid``,
    ``solids`` and ``box``, ``[xmin, ymin, zmin, xmax, ymax, zmax]`` in
    mm), ``step`` (the STEP read back, the same three) and ``sheet``
    (whether the model holds its ``Parameters`` spreadsheet).

    Returns:
        Standalone Python source for execution inside FreeCAD.
    """
    return (
        '"""Generated by CNCguitarwizard. Do not edit manually."""\n\n'
        "import json\n"
        "import os\n\n"
        "import FreeCAD as App\n"
        "import Part\n\n"
        "# Beside this script, wherever it is run.\n"
        "FOLDER = (\n"
        "    os.path.dirname(os.path.abspath(__file__))\n"
        '    if "__file__" in globals()\n'
        "    else os.getcwd()\n"
        ")\n\n\n"
        "def measured(shape):\n"
        '    """Return whether a shape is valid, its solids and its box."""\n'
        "    box = shape.BoundBox\n"
        "    return {\n"
        '        "valid": shape.isValid(),\n'
        '        "solids": len(shape.Solids),\n'
        '        "box": [box.XMin, box.YMin, box.ZMin, box.XMax, box.YMax, box.ZMax],\n'
        "    }\n\n\n"
        'document = App.openDocument(os.path.join(FOLDER, "Prototype001.FCStd"))\n'
        "parts = {\n"
        "    part.Name: measured(part.Shape)\n"
        "    for part in document.Objects\n"
        '    if part.isDerivedFrom("Part::Feature")\n'
        "    and part.Visibility\n"
        "    and not part.Shape.isNull()\n"
        "    and part.Shape.Solids\n"
        "}\n"
        'step = Part.read(os.path.join(FOLDER, "Prototype001.step"))\n'
        'sheet = document.getObject("Parameters")\n'
        "print(\n"
        f"    {MEASURED_PREFIX!r}\n"
        "    + json.dumps(\n"
        "        {\n"
        '            "parts": parts,\n'
        '            "step": measured(step),\n'
        '            "sheet": sheet is not None\n'
        '            and sheet.TypeId == "Spreadsheet::Sheet",\n'
        "        }\n"
        "    )\n"
        ")\n"
    )


def read_measured(stdout: str) -> dict[str, Any] | None:
    """Return the measurements a measuring script printed, if it did.

    Args:
        stdout: What FreeCAD printed while running the script.

    Returns:
        The JSON object of the last ``MEASURED_PREFIX`` line, or ``None``
        when there is none (or it does not read).
    """
    lines = [line for line in stdout.splitlines() if line.startswith(MEASURED_PREFIX)]
    if not lines:
        return None
    try:
        found = json.loads(lines[-1].removeprefix(MEASURED_PREFIX))
    except json.JSONDecodeError:
        return None
    return found if isinstance(found, dict) else None
